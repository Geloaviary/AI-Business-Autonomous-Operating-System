function analyticsFile() {
  return `'use strict';

/**
 * analytics.js — generated by the Constitutional Engineer.
 * Performance analytics derived from history.js.
 */

class Analytics {
  constructor({ history } = {}) { this.history = history; }

  successRate() {
    const runs = this.history?.all().filter((r) => r.kind === 'RUN') || [];
    if (runs.length === 0) return null;
    return runs.filter((r) => r.payload.outcome === 'SUCCESS').length / runs.length;
  }

  averageDurationMs() {
    const runs = this.history?.all().filter((r) => r.kind === 'RUN' && typeof r.payload.durationMs === 'number') || [];
    if (runs.length === 0) return null;
    return runs.reduce((sum, r) => sum + r.payload.durationMs, 0) / runs.length;
  }
}

module.exports = { Analytics };
`;
}

