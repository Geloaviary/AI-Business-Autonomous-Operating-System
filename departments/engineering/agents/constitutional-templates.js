function selfHealthFile(plan) {
  const className = `${pascalCase(plan.departmentName)}Health`;
  return `'use strict';

/**
 * ${plan.departmentName}.js — generated by the Constitutional Engineer.
 * Self health monitoring for the ${plan.departmentName} department —
 * the same role engineering.js plays for Engineering itself.
 */

const config = require('./config');

class ${className} {
  constructor({ events, memory, qadClient } = {}) {
    this.events = events;
    this.memory = memory;
    this.qadClient = qadClient;
    this.failureCount = 0;
    this.events?.on('Failure', () => { this.failureCount += 1; });
  }

  determineOverallStatus() {
    if (this.failureCount >= config.health.unhealthyFailureThreshold) return 'UNHEALTHY';
    if (this.failureCount >= config.health.degradedFailureThreshold) return 'DEGRADED';
    return 'HEALTHY';
  }

  async runDiagnostics() {
    const report = {
      status: this.determineOverallStatus(),
      failureCount: this.failureCount,
      checkedAt: new Date().toISOString()
    };
    this.events?.publish('HealthCheck', report);
    return report;
  }
}

module.exports = { ${className} };
`;
}

