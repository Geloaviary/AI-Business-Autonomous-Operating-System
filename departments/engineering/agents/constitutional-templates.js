function registryFile() {
  return `'use strict';

/**
 * registry.js — generated by the Constitutional Engineer.
 * Dependency registry so this department's own modules stay decoupled.
 */

const { RegistryError } = require('./errors');

class Registry {
  constructor() { this._entries = new Map(); }

  _namespace(ns) {
    if (!this._entries.has(ns)) this._entries.set(ns, new Map());
    return this._entries.get(ns);
  }

  register(namespace, name, value) {
    const bucket = this._namespace(namespace);
    if (bucket.has(name)) throw new RegistryError(\`"\${name}" already registered in "\${namespace}"\`);
    bucket.set(name, value);
    return this;
  }

  resolve(namespace, name) {
    const bucket = this._entries.get(namespace);
    if (!bucket || !bucket.has(name)) throw new RegistryError(\`No entry "\${name}" in "\${namespace}"\`);
    return bucket.get(name);
  }

  has(namespace, name) {
    const bucket = this._entries.get(namespace);
    return !!bucket && bucket.has(name);
  }

  list(namespace) {
    const bucket = this._entries.get(namespace);
    return bucket ? Array.from(bucket.keys()) : [];
  }
}

module.exports = { Registry };
`;
}

