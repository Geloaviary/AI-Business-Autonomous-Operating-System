function artifactFile(plan) {
  return `'use strict';

/**
 * artifact.js — generated by the Constitutional Engineer for the
 * ${plan.departmentName} department. Immutable unit of work this department
 * produces. Never mutated after creation — repair.js always creates a new
 * artifact with a parentArtifactId, matching Engineering's own pattern.
 */

const crypto = require('crypto');
const { ArtifactError } = require('./errors');

class Artifact {
  constructor(spec) {
    if (!spec || !spec.contractId || !spec.payload) {
      throw new ArtifactError('Artifact requires contractId and payload', { spec });
    }
    this.id = \`artifact_\${crypto.randomUUID()}\`;
    this.contractId = spec.contractId;
    this.departmentName = '${plan.departmentName}';
    this.payload = Object.freeze(spec.payload);
    this.parentArtifactId = spec.parentArtifactId || null;
    this.createdAt = new Date().toISOString();
    this.checksum = this._computeChecksum();
    Object.freeze(this);
  }

  _computeChecksum() {
    return crypto.createHash('sha256').update(JSON.stringify(this.payload)).digest('hex');
  }

  summary() {
    return {
      id: this.id, contractId: this.contractId, departmentName: this.departmentName,
      parentArtifactId: this.parentArtifactId, checksum: this.checksum, createdAt: this.createdAt
    };
  }
}

module.exports = { Artifact };
`;
}

function validatorsFile(plan) {
  return `'use strict';

/**
 * validators.js — generated by the Constitutional Engineer for the
 * ${plan.departmentName} department. Internal quality gate before
 * submission to the Quality Assurance Director.
 */

function checkContract(contract) {
  const errors = [];
  if (!contract?.objective) errors.push('Contract is missing an objective');
  if (!contract?.requestedBy) errors.push('Contract is missing requestedBy');
  return errors;
}

function checkArtifact(artifact) {
  const errors = [];
  if (!artifact?.payload) errors.push('Artifact is missing a payload');
  if (!artifact?.checksum) errors.push('Artifact is missing a checksum');
  return errors;
}

function validateArtifactCandidate({ contract, artifact }) {
  const issues = [
    ...checkContract(contract).map((message) => ({ category: 'contract', message })),
    ...checkArtifact(artifact).map((message) => ({ category: 'artifact', message }))
  ];
  return { passed: issues.length === 0, issues, checkedAt: new Date().toISOString() };
}

module.exports = { validateArtifactCandidate, checkContract, checkArtifact };
`;
}

function repairFile(plan) {
  return `'use strict';

/**
 * repair.js — generated by the Constitutional Engineer for the
 * ${plan.departmentName} department. Handles rejected artifacts by
 * producing a NEW artifact (never mutating the rejected one), matching
 * Engineering's own immutability rule.
 */

const { Artifact } = require('./artifact');
const { RepairExhaustedError } = require('./errors');
const config = require('./config');

class RepairCoordinator {
  constructor({ events } = {}) {
    this.events = events;
  }

  async repair({ artifact, rejectionReport, attempt }) {
    if (attempt > config.execution.maxRepairAttempts) {
      throw new RepairExhaustedError('Maximum repair attempts exceeded', {
        artifactId: artifact.id, attempt
      });
    }
    this.events?.publish('RepairStarted', { artifactId: artifact.id, attempt });

    // Generic repair: carry the payload forward with issues annotated for
    // visibility. Department-specific repair logic can override this once
    // this department has its own specialized workforce.
    const repaired = new Artifact({
      contractId: artifact.contractId,
      payload: { ...artifact.payload, _repairNotes: (rejectionReport.issues || []).map((i) => i.message) },
      parentArtifactId: artifact.id
    });

    this.events?.publish('RepairCompleted', { previousArtifactId: artifact.id, newArtifactId: repaired.id, attempt });
    return { artifact: repaired, actions: (rejectionReport.issues || []).map((i) => \`Noted: \${i.message}\`) };
  }
}

module.exports = { RepairCoordinator };
`;
}

