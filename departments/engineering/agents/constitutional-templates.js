function memoryFile(plan) {
  return `'use strict';

/**
 * memory.js — generated by the Constitutional Engineer for the
 * ${plan.departmentName} department. READ-ONLY interface to Platform
 * Memory — the standalone, shared BAOS service, not owned by this
 * department. This department never writes here directly — only the
 * Quality Assurance Director may commit certified knowledge.
 */

const { MemoryAccessError } = require('./errors');

class DepartmentMemory {
  constructor(platformMemory) {
    this.platformMemory = platformMemory;
  }

  /**
   * Finds real precedent for a topic — not just a pointer to a certified
   * artifact, but the actual prior contribution a specialist can build on.
   * Certified submissions from this department's own workforce carry a
   * \`content.contributions\` array (see the Quality Assurance Director's
   * manager.js — \`_extractKnowledge\`); this pulls out the specific past
   * contribution(s) whose responsibility matches the topic being asked
   * about now, so a specialist consulting Platform Memory gets something
   * it can actually cite, not a generic label.
   */
  async findRelevantKnowledge(topic) {
    if (!topic) throw new MemoryAccessError('findRelevantKnowledge requires a topic');
    if (!this.platformMemory) return [];
    try {
      const entries = await this.platformMemory.query({ departmentName: '${plan.departmentName}', topic });
      const precedent = [];
      for (const entry of entries) {
        const contributions = entry.content?.contributions || [];
        for (const contribution of contributions) {
          if (contribution.responsibility && contribution.responsibility.toLowerCase().includes(String(topic).toLowerCase())) {
            precedent.push({ certificateId: entry.certificateId, committedAt: entry.committedAt, ...contribution });
          }
        }
      }
      // Fall back to the raw entries if nothing matched at the fine-grained
      // level — still better than nothing, just less specific.
      return precedent.length > 0 ? precedent : entries;
    } catch (err) {
      throw new MemoryAccessError('Failed to query Platform Memory', { cause: err.message });
    }
  }
}

module.exports = { DepartmentMemory };
`;
}

